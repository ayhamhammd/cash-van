#!/usr/bin/env bash
# Generates the CRM's RSA signing keypair and writes .env.suite for the local
# docker suite.
#
# The keypair is NOT committed and NOT baked into an image: it is the thing that
# lets this CRM mint tokens the other products trust, so each environment needs
# its own. Re-running invalidates every issued token, which is the intended way
# to rotate.
set -euo pipefail
cd "$(dirname "$0")/.."

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 -out "$tmp/private.pem" 2>/dev/null
openssl rsa -pubout -in "$tmp/private.pem" -out "$tmp/public.pem" 2>/dev/null

{
  echo "# Generated by scripts/gen-crm-keys.sh — do not commit."
  echo "CRM_AUTH_PRIVATE_KEY=\"$(awk '{printf "%s\\n", $0}' "$tmp/private.pem")\""
  echo "CRM_AUTH_PUBLIC_KEY=\"$(awk '{printf "%s\\n", $0}' "$tmp/public.pem")\""
} > .env.suite

echo "Wrote .env.suite"
echo "Now: docker compose -f docker-compose.suite.yml --env-file .env.suite up -d --build"
